//! Seeded initial layouts for the deterministic UMAP core path.
//!
//! The random initializer deliberately stops at the observed compatibility
//! boundary: row-major MT19937 uniform draws over `[-10, 10)`, conversion to
//! `f32`, and per-column rescaling to `[0, 10]`.  Optimization and any later
//! layout processing belong to callers.

use std::{cmp::Ordering, fmt};

use crate::numeric::pairwise_sum;
use crate::rng::Mt19937;

/// Input or normalization failures for seeded layout initialization.
#[derive(Clone, Debug, PartialEq)]
pub enum InitializationError {
    /// The supplied data length does not match `n_rows * n_components`.
    InvalidShape {
        /// Number of rows in the claimed row-major matrix.
        n_rows: usize,
        /// Number of columns in the claimed row-major matrix.
        n_components: usize,
        /// Number of values supplied by the caller.
        values: usize,
    },
    /// `n_rows * n_components` overflowed `usize`.
    ShapeOverflow {
        /// Number of rows in the claimed row-major matrix.
        n_rows: usize,
        /// Number of columns in the claimed row-major matrix.
        n_components: usize,
    },
    /// A layout value was not finite.
    NonFiniteValue {
        /// Flat row-major index of the invalid value.
        index: usize,
        /// The invalid value.
        value: f32,
    },
    /// A column has no finite range for normalization.
    ZeroColumnSpan {
        /// Column whose maximum and minimum are equal in `f32` arithmetic.
        column: usize,
    },
}

impl fmt::Display for InitializationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidShape {
                n_rows,
                n_components,
                values,
            } => write!(
                formatter,
                "layout shape {n_rows}x{n_components} does not match {values} values"
            ),
            Self::ShapeOverflow {
                n_rows,
                n_components,
            } => write!(
                formatter,
                "layout shape {n_rows}x{n_components} overflows the addressable length"
            ),
            Self::NonFiniteValue { index, value } => {
                write!(
                    formatter,
                    "layout value at flat index {index} is not finite: {value}"
                )
            }
            Self::ZeroColumnSpan { column } => {
                write!(formatter, "layout column {column} has zero span")
            }
        }
    }
}

impl std::error::Error for InitializationError {}

/// Draw and normalize a deterministic row-major random initial layout.
///
/// Each value is generated by `Mt19937::next_f64`, mapped as
/// `-10.0 + 20.0 * draw` in `f64`, and then cast to `f32`.  Once all values
/// have been generated, [`normalize_columns`] applies the per-column
/// operation `10.0_f32 * (value - min) / (max - min)`.  The operation order
/// and `f32` rounding are intentional compatibility details.
///
/// A column with a zero `f32` span is rejected instead of producing a NaN
/// layout.  The returned values remain row-major with shape
/// `n_rows x n_components`.
pub fn random_initialization(
    seed: u32,
    n_rows: usize,
    n_components: usize,
) -> Result<Vec<f32>, InitializationError> {
    random_initialization_with_rng(&mut Mt19937::new(seed), n_rows, n_components)
}

/// Draw and normalize a random initial layout using an existing caller RNG.
///
/// Uses the same draws as [`random_initialization`]. The generator remains
/// positioned after the uniform draws for subsequent layout sampling.
pub fn random_initialization_with_rng(
    generator: &mut Mt19937,
    n_rows: usize,
    n_components: usize,
) -> Result<Vec<f32>, InitializationError> {
    let length = checked_length(n_rows, n_components)?;
    let mut values = uniform_layout(generator, length);

    normalize_columns(&mut values, n_rows, n_components)?;
    Ok(values)
}

/// Normalize finite row-major values independently in each column.
///
/// For every column, the minimum and maximum are computed in `f32`
/// arithmetic.  Each element is then replaced in place by
/// `10.0_f32 * (value - min) / (max - min)`, in that exact order.  The input
/// must have non-zero dimensions, the claimed shape must fit `data`, and all
/// values must be finite.  A column whose `max - min` is zero is reported as
/// [`InitializationError::ZeroColumnSpan`].
pub fn normalize_columns(
    data: &mut [f32],
    n_rows: usize,
    n_components: usize,
) -> Result<(), InitializationError> {
    let length = checked_length(n_rows, n_components)?;
    if n_rows == 0 || n_components == 0 || data.len() != length {
        return Err(InitializationError::InvalidShape {
            n_rows,
            n_components,
            values: data.len(),
        });
    }

    validate_finite(data)?;

    // Validate every span before mutating any column so an error leaves the
    // caller's input untouched.
    for column in 0..n_components {
        let mut minimum = f32::INFINITY;
        let mut maximum = f32::NEG_INFINITY;
        for row in 0..n_rows {
            let value = data[row * n_components + column];
            minimum = minimum.min(value);
            maximum = maximum.max(value);
        }

        let span = maximum - minimum;
        if span == 0.0 {
            return Err(InitializationError::ZeroColumnSpan { column });
        }
    }

    for column in 0..n_components {
        let mut minimum = f32::INFINITY;
        let mut maximum = f32::NEG_INFINITY;
        for row in 0..n_rows {
            let value = data[row * n_components + column];
            minimum = minimum.min(value);
            maximum = maximum.max(value);
        }
        let span = maximum - minimum;
        for row in 0..n_rows {
            let index = row * n_components + column;
            let value = data[index];
            data[index] = 10.0_f32 * (value - minimum) / span;
        }
    }

    Ok(())
}

pub(crate) fn checked_length(
    n_rows: usize,
    n_components: usize,
) -> Result<usize, InitializationError> {
    n_rows
        .checked_mul(n_components)
        .ok_or(InitializationError::ShapeOverflow {
            n_rows,
            n_components,
        })
}

pub(crate) fn uniform_layout(generator: &mut Mt19937, length: usize) -> Vec<f32> {
    (0..length)
        .map(|_| (-10.0 + 20.0 * generator.next_f64()) as f32)
        .collect()
}

pub(crate) fn validate_finite(layout: &[f32]) -> Result<(), InitializationError> {
    if let Some((index, &value)) = layout
        .iter()
        .enumerate()
        .find(|(_, value)| !value.is_finite())
    {
        return Err(InitializationError::NonFiniteValue { index, value });
    }
    Ok(())
}

pub(crate) fn write_mean<'a>(output: &mut [f32], rows: impl Iterator<Item = &'a [f32]>) {
    let mut count = 0;
    for row in rows {
        for (coordinate, &value) in output.iter_mut().zip(row) {
            *coordinate += value;
        }
        count += 1;
    }
    for coordinate in output {
        *coordinate /= count as f32;
    }
}

pub(crate) fn has_coincident_rows(layout: &[f32], width: usize) -> bool {
    let mut rows: Vec<_> = layout.chunks_exact(width).collect();
    rows.sort_unstable_by(|left, right| {
        left.iter()
            .zip(*right)
            .map(|(left, right)| {
                if left == right {
                    Ordering::Equal
                } else {
                    left.total_cmp(right)
                }
            })
            .find(|&order| order != Ordering::Equal)
            .unwrap_or(Ordering::Equal)
    });
    rows.windows(2).any(|pair| pair[0] == pair[1])
}

pub(crate) fn coincident_layout_noise_scale(layout: &[f32], width: usize) -> f64 {
    let count = layout.len() / width;
    let mut nearest = vec![f64::INFINITY; count];
    let mut squared_components = Vec::with_capacity(width);
    for (left_index, left) in layout.chunks_exact(width).enumerate() {
        for (right_index, right) in layout.chunks_exact(width).enumerate().skip(left_index + 1) {
            squared_components.clear();
            squared_components.extend(left.iter().zip(right).map(|(&left, &right)| {
                let difference = f64::from(left) - f64::from(right);
                difference * difference
            }));
            let squared_distance = pairwise_sum(&squared_components);
            nearest[left_index] = nearest[left_index].min(squared_distance);
            nearest[right_index] = nearest[right_index].min(squared_distance);
        }
    }
    for value in &mut nearest {
        *value = value.sqrt();
    }
    0.001 * (pairwise_sum(&nearest) / count as f64)
}

#[cfg(test)]
mod tests {
    use super::{InitializationError, normalize_columns, random_initialization};

    #[test]
    fn normalizes_columns_in_row_major_order() {
        let mut data = [1.0_f32, 2.0, 2.0, 5.0, 4.0, 11.0];
        normalize_columns(&mut data, 3, 2).expect("valid finite matrix");

        assert_eq!(data[0].to_bits(), 0x0000_0000);
        assert_eq!(data[1].to_bits(), 0x0000_0000);
        assert_eq!(data[2].to_bits(), 0x4055_5555);
        assert_eq!(data[3].to_bits(), 0x4055_5555);
        assert_eq!(data[4].to_bits(), 0x4120_0000);
        assert_eq!(data[5].to_bits(), 0x4120_0000);
    }

    #[test]
    fn random_initialization_is_seeded_and_normalized() {
        let expected = [0x410d_4a69_u32, 0x4120_0000, 0x0000_0000];
        let layout = random_initialization(5489, 3, 1).expect("non-degenerate seeded layout");
        assert_eq!(layout.len(), expected.len());
        for (value, expected_bits) in layout.iter().zip(expected) {
            assert_eq!(value.to_bits(), expected_bits);
        }
        assert_eq!(layout, random_initialization(5489, 3, 1).unwrap());
    }

    #[test]
    fn matches_observed_seeded_layout_fixture() {
        let expected = [
            1_082_885_031,
            1_092_368_893,
            1_091_318_821,
            1_085_147_600,
            1_070_958_481,
            0,
            1_055_685_941,
            1_091_279_779,
            1_088_737_803,
            1_087_966_787,
            0,
            1_092_616_192,
            1_092_616_192,
            1_060_190_299,
            1_073_624_946,
            1_051_487_427,
        ];
        let layout = random_initialization(42, 8, 2).expect("observed fixture is non-degenerate");
        let actual = layout
            .iter()
            .map(|value| value.to_bits())
            .collect::<Vec<_>>();
        assert_eq!(actual, expected);
    }

    #[test]
    fn matches_observed_explicit_column_normalization_fixture() {
        let mut data = [
            -4.0_f32, -2.0, 0.0, 1.0, 3.0, 4.0, 8.0, 2.0, 10.0, 9.0, 17.0, 6.0, 20.0, 15.0, 30.0,
            25.0,
        ];
        let expected = [
            0,
            0,
            1_066_833_559,
            1_066_285_284,
            1_073_988_548,
            1_074_673_892,
            1_080_156_642,
            1_069_392_175,
            1_082_377_156,
            1_082_285_777,
            1_086_694_822,
            1_077_780_783,
            1_088_545_250,
            1_086_946_114,
            1_092_616_192,
            1_092_616_192,
        ];

        normalize_columns(&mut data, 8, 2).expect("valid finite explicit initialization");
        let actual = data.iter().map(|value| value.to_bits()).collect::<Vec<_>>();
        assert_eq!(actual, expected);
    }

    #[test]
    fn rejects_shape_non_finite_and_zero_span() {
        assert_eq!(
            normalize_columns(&mut [0.0, 1.0, 2.0], 2, 2),
            Err(InitializationError::InvalidShape {
                n_rows: 2,
                n_components: 2,
                values: 3,
            })
        );
        assert!(matches!(
            normalize_columns(&mut [0.0, f32::NAN, 2.0, 3.0], 2, 2),
            Err(InitializationError::NonFiniteValue { index: 1, value }) if value.is_nan()
        ));
        assert_eq!(
            normalize_columns(&mut [1.0, 2.0, 1.0, 3.0], 2, 2),
            Err(InitializationError::ZeroColumnSpan { column: 0 })
        );
    }

    #[test]
    fn rejects_empty_random_layout_without_claiming_compatibility() {
        assert_eq!(
            random_initialization(5489, 1, 0),
            Err(InitializationError::InvalidShape {
                n_rows: 1,
                n_components: 0,
                values: 0,
            })
        );
        assert_eq!(
            random_initialization(5489, 1, 1),
            Err(InitializationError::ZeroColumnSpan { column: 0 })
        );
    }
}
